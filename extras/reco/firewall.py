# Endpoints
# =============================================================================

@firewall_bp.route("/analyze", methods=["POST"])
def analyze():
    """POST /api/firewall/analyze — テキストレベルを判定"""
    _init_state()

    data = request.get_json(silent=True)
    if not data or "text" not in data:
        return jsonify({
            "error": "リクエストボディに 'text' フィールドが必要です",
            "usage": {"method": "POST", "body": {"text": "分析するテキスト", "k": "(optional) float"}}
        }), 400

    text = data["text"]
    if not isinstance(text, str) or len(text.strip()) == 0:
        return jsonify({"error": "テキストが空です"}), 400

    k = data.get("k", K_DEFAULT)
    if not isinstance(k, (int, float)) or k <= 0:
        k = K_DEFAULT

    result = compute_confidence(text, k=k)

    _state["total_requests"] += 1
    _state["last_analysis"] = {
        "timestamp": time.time(),
        "level": result["level"],
        "confidence": result["confidence"],
    }

    return jsonify({
        "firewall": "RECO",
        "version": FIREWALL_VERSION,
        "result": result,
    })


@firewall_bp.route("/health", methods=["GET"])
def health():
    """GET /api/firewall/health — ヘルスチェック"""
    _init_state()
    return jsonify({
        "status": "healthy",
        "name": "RECO — AI Firewall",
        "version": FIREWALL_VERSION,
    })


@firewall_bp.route("/status", methods=["GET"])
def status():
    """GET /api/firewall/status — 現在の判定状態"""
    _init_state()
    uptime = time.time() - _state["started_at"] if _state["started_at"] else 0
    return jsonify({
        "name": "RECO — AI Firewall",
        "version": FIREWALL_VERSION,
        "status": FIREWALL_STATUS,
        "total_requests": _state["total_requests"],
        "uptime_seconds": round(uptime, 1),
        "last_analysis": _state["last_analysis"],
    })


