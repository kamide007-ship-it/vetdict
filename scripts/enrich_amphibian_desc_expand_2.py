def apply_enrichments() -> None:
    import fcntl
    import shutil
    import tempfile

    # Use exclusive file lock to prevent concurrent writes
    lock_path = JSON_PATH + ".lock"
    lock_fd = open(lock_path, "w")
    fcntl.flock(lock_fd.fileno(), fcntl.LOCK_EX)

    try:
        # Read fresh from git to avoid corrupted working copy
        import subprocess

        result = subprocess.run(
            ["git", "show", "HEAD:diseases_all_species.json"],
            capture_output=True,
            cwd=os.path.dirname(JSON_PATH),
        )
        if result.returncode == 0:
            data = json.loads(result.stdout.decode("utf-8"))
        else:
            with open(JSON_PATH, encoding="utf-8") as f:
                data = json.load(f)

        updated = 0
        for entry in data:
            eid = entry.get("id")
            if eid in ENRICHMENTS:
                entry["description_ja"] = ENRICHMENTS[eid]
                updated += 1

        missing = set(ENRICHMENTS) - {e.get("id") for e in data}
        if missing:
            print(f"WARNING: {len(missing)} IDs in ENRICHMENTS not found in JSON:")
            for m in sorted(missing):
                print(f"  {m}")

        # Write to temp file in /tmp
        tmp_fd, tmp_path = tempfile.mkstemp(suffix=".json", prefix="diseases_amphi_")
        try:
            with os.fdopen(tmp_fd, "w", encoding="utf-8") as f:
                json.dump(data, f, ensure_ascii=False, indent=2)

            # Verify temp file is valid
            with open(tmp_path, encoding="utf-8") as f:
                verified = json.load(f)
            assert len(verified) == len(data), "Entry count mismatch"

            # Atomic copy
            shutil.copy2(tmp_path, JSON_PATH)
        finally:
            if os.path.exists(tmp_path):
                os.remove(tmp_path)

        print(f"Updated {updated}/{len(ENRICHMENTS)} amphibian description_ja entries")
    finally:
        fcntl.flock(lock_fd.fileno(), fcntl.LOCK_UN)
        lock_fd.close()
        if os.path.exists(lock_path):
            os.remove(lock_path)

    # Verify lengths
    too_short = []
    too_long = []
    for eid, desc in ENRICHMENTS.items():
        length = len(desc)
        if length < 150:
            too_short.append((eid, length))
        elif length > 300:
            too_long.append((eid, length))

    if too_short:
        print(f"\nWARNING: {len(too_short)} entries below 150 chars:")
        for eid, length in too_short:
            print(f"  {eid}: {length}c")
    if too_long:
        print(f"\nWARNING: {len(too_long)} entries above 300 chars:")
        for eid, length in too_long:
            print(f"  {eid}: {length}c")

    if not too_short and not too_long:
        print("\nAll entries within target range (150-300 chars)")


if __name__ == "__main__":
    apply_enrichments()
