def main() -> None:
    data = json.loads(JSON_PATH.read_text(encoding="utf-8"))

    timestamp = datetime.utcnow().strftime("%Y%m%d_%H%M%S")
    backup = JSON_PATH.with_suffix(f".json.backup_{timestamp}_pre_signs_improvement")
    if not backup.exists():
        shutil.copy2(JSON_PATH, backup)
        print(f"backup written: {backup.name}")

    stats = {
        "total": len(data),
        "templated": 0,
        "fixed_from_kb": 0,
        "fixed_from_patho": 0,
        "still_templated": 0,
    }

    for entry in data:
        cs = entry.get("clinical_signs_ja") or ""
        if not is_templated(cs):
            continue
        stats["templated"] += 1

        new_signs = derive_clinical_signs(entry)
        if new_signs is None:
            stats["still_templated"] += 1
            continue

        disease_name = extract_disease_name(cs) or (entry.get("name_ja") or "").strip()
        if _kb_lookup(disease_name) is not None:
            stats["fixed_from_kb"] += 1
        else:
            stats["fixed_from_patho"] += 1

        entry["clinical_signs_ja"] = new_signs
        entry["clinical_signs_backfilled_at"] = datetime.utcnow().isoformat()

    JSON_PATH.write_text(
        json.dumps(data, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )

    print("=== clinical_signs_ja improvement ===")
    for k, v in stats.items():
        print(f"  {k}: {v}")


if __name__ == "__main__":
    main()
