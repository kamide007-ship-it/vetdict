def is_templated(cs: str | None) -> bool:
    if not cs:
        return False
    return GENERIC_TEMPLATE in cs or "の臨床兆候は重症度と病期により異なる" in cs


def extract_disease_name(cs: str) -> str | None:
    m = TEMPLATE_RE.match(cs)
    if m:
        return m.group(1).strip()
    return None


