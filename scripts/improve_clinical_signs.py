def extract_signs_from_text(text: str | None) -> list[str]:
    if not text:
        return []
    found: list[str] = []
    for kw in SIGN_KEYWORDS:
        if kw in text and kw not in found:
            found.append(kw)
    return found


def _normalize(name: str) -> str:
    """検索用に名前を正規化（カタカナ↔ひらがな・括弧種別の除去）。"""
    base = re.sub(r"[（(].*?[)）]\s*$", "", name).strip()
    return base


