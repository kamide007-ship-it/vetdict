def fix_file(path: Path) -> int:
    """Fix untranslated ja fields in a species disease file. Return count of fixes."""
    text = path.read_text(encoding="utf-8")
    count = 0

    def replace_ja(m: re.Match) -> str:
        nonlocal count
        en_val = m.group(1)
        ja_val = TRANSLATIONS.get(en_val)
        if ja_val and ja_val != en_val:
            count += 1
            return f'"ja": "{ja_val}"'
        return m.group(0)

    # Match "ja": "EnglishText" where value starts with uppercase
    new_text = re.sub(r'"ja": "([A-Z][a-zA-Z ]+(?:\([A-Za-z ]+\))?)"', replace_ja, text)
    if count > 0:
        path.write_text(new_text, encoding="utf-8")
    return count


def main():
    species_dir = Path(__file__).resolve().parent.parent / "api" / "species"
    total = 0
    for f in sorted(species_dir.glob("*_diseases.py")):
        n = fix_file(f)
        if n:
            print(f"  {f.name}: {n} translations applied")
            total += n
    print(f"\nTotal: {total} translations applied across all species files")
    return 0 if total > 0 else 1


if __name__ == "__main__":
    sys.exit(main())
