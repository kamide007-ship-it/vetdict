def apply_enrichments() -> None:
    for attempt in range(3):
        try:
            with open(JSON_PATH, encoding="utf-8") as f:
                content = f.read()
            decoder = json.JSONDecoder()
            data, _ = decoder.raw_decode(content)
            break
        except (json.JSONDecodeError, ValueError):
            if attempt < 2:
                time.sleep(5)
            else:
                raise
    updated = 0
    for entry in data:
        eid = entry.get("id")
        if eid in ENRICHMENTS:
            for k, v in ENRICHMENTS[eid].items():
                entry[k] = v
            updated += 1
    with open(JSON_PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"Updated {updated}/{len(ENRICHMENTS)} entries")

    # Verify lengths
    warn_count = 0
    for eid, fields in ENRICHMENTS.items():
        dja = fields.get("diagnosis_ja", "")
        length = len(dja)
        if not (150 <= length <= 350):
            print(f"  WARNING: {eid} diagnosis_ja length={length}")
            warn_count += 1
    if warn_count == 0:
        print("All entries within 150-350 character range.")


if __name__ == "__main__":
    apply_enrichments()
