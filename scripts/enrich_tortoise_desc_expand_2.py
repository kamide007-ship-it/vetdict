def apply_enrichments() -> None:
    import gc
    import shutil
    import subprocess

    # Read from git to avoid filesystem corruption issues with large files
    result = subprocess.run(
        ["git", "show", "HEAD:diseases_all_species.json"],
        capture_output=True,
        cwd=os.path.dirname(JSON_PATH),
    )
    if result.returncode != 0:
        # Fallback to file read
        with open(JSON_PATH, encoding="utf-8") as f:
            data = json.load(f)
    else:
        content = result.stdout.decode("utf-8")
        data = json.loads(content)
        del content
    gc.collect()
    print(f"Loaded {len(data)} entries")

    updated = 0
    for entry in data:
        eid = entry.get("id")
        if eid in ENRICHMENTS:
            for k, v in ENRICHMENTS[eid].items():
                entry[k] = v
            updated += 1
    missing = set(ENRICHMENTS) - {e.get("id") for e in data}
    if missing:
        print(f"WARNING: {len(missing)} IDs not found: {sorted(missing)}")

    # Write to /tmp first (avoids overlay fs issues), then copy back
    tmp_path = "/tmp/diseases_enriched.json"
    with open(tmp_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    del data
    gc.collect()

    # Verify temp file
    file_size = os.path.getsize(tmp_path)
    if file_size < 30_000_000:
        raise RuntimeError(f"Output file too small: {file_size} bytes")
    with open(tmp_path, encoding="utf-8") as f:
        json.load(f)

    # Copy to final location
    shutil.copy2(tmp_path, JSON_PATH)
    os.remove(tmp_path)
    print(f"Updated {updated}/{len(ENRICHMENTS)} entries (file: {file_size:,} bytes)")


if __name__ == "__main__":
    apply_enrichments()
