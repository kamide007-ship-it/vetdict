def main() -> None:
    print(f"Loading {JSON_PATH} ...")
    # Use binary read to avoid filesystem text-mode caching issues
    with open(JSON_PATH, "rb") as f:
        raw = f.read()
    text = raw.decode("utf-8")
    data = json.loads(text)
    print(f"  Loaded {len(data)} entries from {len(raw)} bytes")

    if not isinstance(data, list):
        print("ERROR: top-level is not a list")
        sys.exit(1)

    id_to_idx: dict[str, int] = {}
    for i, entry in enumerate(data):
        eid = entry.get("id", "")
        if eid in ENRICHMENTS:
            id_to_idx[eid] = i

    updated = 0
    missing_ids = []
    for eid, fields in ENRICHMENTS.items():
        if eid not in id_to_idx:
            missing_ids.append(eid)
            continue
        idx = id_to_idx[eid]
        for field, value in fields.items():
            data[idx][field] = value
        updated += 1

    if missing_ids:
        print(f"WARNING: {len(missing_ids)} IDs not found: {missing_ids}")

    print(f"Updated {updated}/{len(ENRICHMENTS)} entries.")

    # Write to temp file then replace — all in binary mode
    print("Serializing and writing...")
    tmp_path = JSON_PATH + ".tmp"
    with open(tmp_path, "wb") as f:
        f.write(b"[\n")
        for i, entry in enumerate(data):
            line = json.dumps(entry, ensure_ascii=False)
            if i < len(data) - 1:
                f.write((line + ",\n").encode("utf-8"))
            else:
                f.write((line + "\n").encode("utf-8"))
        f.write(b"]\n")
        f.flush()
        os.fsync(f.fileno())
    print(f"  Temp file written: {os.path.getsize(tmp_path)} bytes")

    # Replace original
    os.replace(tmp_path, JSON_PATH)
    print(f"  Replaced original: {os.path.getsize(JSON_PATH)} bytes")

    # Verify from disk (binary read)
    print("Verifying from disk...")
    with open(JSON_PATH, "rb") as f:
        verify_raw = f.read()
    verify_data = json.loads(verify_raw.decode("utf-8"))
    print(f"  Disk verification: {len(verify_data)} entries")

    short_entries = []
    for eid in ENRICHMENTS:
        if eid not in id_to_idx:
            continue
        idx = id_to_idx[eid]
        desc = verify_data[idx].get("description_ja", "")
        length = len(desc)
        if length < 150:
            short_entries.append((eid, length, desc[:60]))

    if short_entries:
        print(f"\nWARNING: {len(short_entries)} entries under 150 chars:")
        for eid, length, preview in short_entries:
            print(f"  {eid}: {length}c — {preview}...")
    else:
        print("\nVerification PASSED: All entries >= 150 chars.")

    # Print stats
    lengths = []
    for eid in ENRICHMENTS:
        if eid not in id_to_idx:
            continue
        idx = id_to_idx[eid]
        desc = verify_data[idx].get("description_ja", "")
        lengths.append(len(desc))
    if lengths:
        print(f"  Min: {min(lengths)}c, Max: {max(lengths)}c, Avg: {sum(lengths)//len(lengths)}c")


