    sp_key = species.lower().replace(" ", "_")
    disease_id = f"{sp_key}_{idx:04d}"

    sp = SPECIES_INFO[species]
    desc = f"{name} in {species}"
    desc_ja = generate_description_ja(name, name_ja, species, category, organ)
    patho = generate_pathophysiology(name, species, category, organ)
    patho_ja = generate_pathophysiology_ja(name, species, category, organ)
