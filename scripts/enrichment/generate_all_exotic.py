def main():
    print("\n=== GENERATING ENRICHED EXOTIC DISEASE DATABASE ===\n")

    with open(DB_PATH, 'r') as f:
        existing = json.load(f)

    exotic_species_set = {"Rabbit", "Hamster", "Guinea Pig", "Chinchilla", "Ferret",
                          "Hedgehog", "Sugar Glider", "Degu", "Bird", "Parakeet",
                          "Parrot", "Reptile", "Tortoise", "Snake", "Lizard",
                          "Amphibian", "Exotic Other"}

    # Keep all non-exotic entries
    non_exotic = [d for d in existing if d.get("species") not in exotic_species_set]
    print(f"Preserving {len(non_exotic)} non-exotic entries")

    # For existing exotic entries, try to preserve good treatment/clinical_signs data
    existing_by_name = {}
    for d in existing:
        if d.get("species") in exotic_species_set:
            key = (d["species"], d["name"])
            if key not in existing_by_name:
                existing_by_name[key] = d

    # Species disease lists
    all_species_diseases = {
        "Rabbit": RABBIT_DISEASES,
        "Hamster": HAMSTER_DISEASES,
        "Guinea Pig": GUINEA_PIG_DISEASES,
        "Chinchilla": CHINCHILLA_DISEASES,
        "Ferret": FERRET_DISEASES,
        "Hedgehog": HEDGEHOG_DISEASES,
        "Sugar Glider": SUGAR_GLIDER_DISEASES,
        "Degu": DEGU_DISEASES,
        "Bird": BIRD_DISEASES,
        "Parakeet": PARAKEET_DISEASES,
        "Parrot": PARROT_DISEASES,
        "Reptile": REPTILE_DISEASES,
        "Tortoise": TORTOISE_DISEASES,
        "Snake": SNAKE_DISEASES,
        "Lizard": LIZARD_DISEASES,
        "Amphibian": AMPHIBIAN_DISEASES,
        "Exotic Other": EXOTIC_OTHER_DISEASES,
    }

    new_exotic = []
    for species, disease_list in all_species_diseases.items():
        for idx, disease_tuple in enumerate(disease_list, 1):
            name = disease_tuple[0]
            name_ja = disease_tuple[1]
            category = disease_tuple[2]
            organ = disease_tuple[3]

            entry = build_disease_entry(idx, name, name_ja, species, category, organ, TIMESTAMP)

            # If existing entry had good treatment/clinical data, preserve it
            key = (species, name)
            if key in existing_by_name:
                old = existing_by_name[key]
                for field in ["treatment", "treatment_ja", "prevention", "prevention_ja",
                              "clinical_signs", "clinical_signs_ja", "diagnosis", "diagnosis_ja",
                              "transmission", "transmission_ja", "prognosis"]:
                    old_val = old.get(field)
                    if old_val and len(str(old_val)) > 50:  # only preserve if substantive
                        entry[field] = old_val

            new_exotic.append(entry)
        print(f"  {species}: {len(disease_list)} diseases generated")

    # Combine all
    all_data = non_exotic + new_exotic
    print(f"\nTotal entries: {len(all_data)}")
    print(f"  Non-exotic: {len(non_exotic)}")
    print(f"  Exotic: {len(new_exotic)}")

    # Write output
    with open(DB_PATH, 'w') as f:
        json.dump(all_data, f, ensure_ascii=False, indent=2)
    print(f"\nWritten to {DB_PATH}")

    # Summary stats
    from collections import Counter
    species_counts = Counter(d["species"] for d in all_data)
    print("\n=== SPECIES SUMMARY ===")
    for sp, cnt in sorted(species_counts.items(), key=lambda x: -x[1]):
        print(f"  {sp}: {cnt}")
    print(f"  TOTAL: {len(all_data)}")

if __name__ == "__main__":
    main()
